/**
 * 数据库集成冒烟测试：better-sqlite3 按 Electron ABI 编译，vitest（纯 Node）加载不了，
 * 所以 db.ts 的删除级联 / GC / 只读打开 / 文件名转义在这里用 Electron-as-Node 跑。
 *   npm run test:db
 */
const { initDatabase } = require(require('path').join(__dirname, '..', 'dist', 'cli', 'core', 'db.js'))
const fs = require('fs'); const path = require('path').join(require('os').tmpdir(), 'vixel-db-smoke.db')
for (const f of [path, path + '-wal', path + '-shm']) fs.rmSync(f, { force: true })
const db = initDatabase(path)
const vec = () => { const v = new Float32Array(768); v[0] = 1; return v }
const assert = (c, m) => { if (!c) { console.log('FAIL', m); process.exitCode = 1 } else console.log('ok  ', m) }
const f = db.addFolder('/tmp/f1')
// two photos share hash h1, one unique h2
const p1 = db.addPhoto(f.id, '/tmp/f1/a.jpg', 'a.jpg', 1, 1, 'h1')
const p2 = db.addPhoto(f.id, '/tmp/f1/b.jpg', 'b.jpg', 1, 1, 'h1')
const p3 = db.addPhoto(f.id, '/tmp/f1/c.jpg', 'c.jpg', 1, 1, 'h2')
db.saveImageVec('h1', vec()); db.saveImageVec('h2', vec()); db.saveOcrText('h2', 'hello world')
const n = (sql) => db.raw.prepare(sql).get().n
assert(n('select count(*) n from image_vec_map') === 2, 'two vectors saved')
// video with a frame photo
const vid = db.addVideo(f.id, '/tmp/f1/v.mp4', 'v.mp4', 10, 1, 'vh', 'video')
const fp = db.addPhoto(f.id, '/tmp/vf/seg0.jpg', 'seg0.jpg', 1, 1, 'fh', { videoId: vid, frameTimeMs: 0 })
db.saveImageVec('fh', vec())
const r = db.cascadeRemoveVideo('/tmp/f1/v.mp4')
assert(r && r.orphanedFrameHashes.join() === 'fh', 'cascadeRemoveVideo returns orphaned frame hash')
assert(n("select count(*) n from image_vec_map where file_hash='fh'") === 0, 'frame vector GCd')
assert(n(`select count(*) n from videos where id=${vid} and deleted_at is not null`) === 1, 'video soft-deleted')
// removeFramesForVideo on second video whose frame shares hash with live photo h1 -> not orphaned
const vid2 = db.addVideo(f.id, '/tmp/f1/w.mp4', 'w.mp4', 10, 1, 'wh', 'video')
db.addPhoto(f.id, '/tmp/vf/w0.jpg', 'w0.jpg', 1, 1, 'h1', { videoId: vid2, frameTimeMs: 0 })
assert(db.removeFramesForVideo(vid2).length === 0, 'shared frame hash not orphaned')
assert(n("select count(*) n from image_vec_map where file_hash='h1'") === 1, 'shared vector kept')
// filename LIKE escaping
assert(db.searchByFileName('_.jpg', 10).length === 0, 'underscore is literal in filename search')
assert(db.searchByFileName('a.jpg', 10).length === 1, 'plain filename search still matches')
// favorites (per hash; duplicates share) + filtered browse
db.setFavorite(['h1'], true)
assert(db.getFavoriteHashes().has('h1') && db.getLibraryCounts().favorites === 1, 'favorite saved and counted once for shared hash')
const fav = db.getRepresentativePhotosFiltered(50, 0, { favorite: true })
assert(fav.length === 1 && fav[0].fileHash === 'h1' && !!fav[0].favorite, 'favorite filter returns the representative with favorite flag')
db.raw.prepare("update photos set width = 4000, height = 3000 where file_hash = 'h1'").run()
db.raw.prepare("update photos set width = 1000, height = 3000 where file_hash = 'h2'").run()
const hashesOf = (f) => db.getRepresentativePhotosFiltered(50, 0, f).map((x) => x.fileHash).sort().join()
assert(hashesOf({ orientation: 'landscape' }) === 'h1', 'orientation landscape')
assert(hashesOf({ orientation: 'panorama' }) === 'h2', 'orientation panorama (3:1 portrait)')
assert(hashesOf({ minPixels: 12000000 }) === 'h1', 'min pixels')
assert(hashesOf({ maxPixels: 4000000 }) === 'h2', 'max pixels')
assert(hashesOf({ durationMax: 30000 }) === '', 'duration filter excludes images')
assert(hashesOf({ orientation: 'landscape', favorite: true, folderId: f.id }) === 'h1', 'combined filters')
db.setFavorite(['h1'], false)
assert(db.getLibraryCounts().favorites === 0, 'unfavorite')
db.setFavorite(['h2'], true)
// hidden_items（近重复清理“隐藏多余”）：网格 / 计数 / 地图都排除，取消隐藏后恢复
const { CleanupStore } = require(require('path').join(__dirname, '..', 'dist', 'cli', 'core', 'cleanupStore.js'))
const store = new CleanupStore(db.raw)
const live = () => db.getRepresentativePhotos(50, 0).map((p) => p.fileHash).sort().join()
const before = db.getLibraryCounts().image
store.hide(['h2'])
assert(!live().includes('h2'), 'hidden item excluded from grid')
assert(db.getLibraryCounts().image === before - 1, 'hidden item excluded from counts')
assert(db.getRepresentativePhotosFiltered(50, 0, { kind: 'image' }).every((p) => p.fileHash !== 'h2'), 'hidden item excluded from filtered grid')
assert(store.listHidden().map((h) => h.fileHash).join() === 'h2', 'listHidden returns the hidden item')
store.unhide(['h2'])
assert(live().includes('h2') && db.getLibraryCounts().image === before, 'unhide restores the item')
assert(store.trashTargets(['h1']).map((x) => x.filePath).sort().join() === '/tmp/f1/a.jpg,/tmp/f1/b.jpg', 'trash targets: every live copy inside the watched folder')
assert(store.trashTargets(['fh', 'nope']).length === 0, 'trash targets: no video frames / unknown hashes')
// 标签：按 hash 挂、计数、改名合并、筛选、搜索、GC
const { TagStore } = require(require('path').join(__dirname, '..', 'dist', 'cli', 'core', 'tagStore.js'))
const tags = new TagStore(db.raw)
const sky = tags.add(['h1', 'h2'], '  Blue   Sky ')
tags.add(['h1'], '花卉')
assert(tags.list().find((x) => x.id === sky).name === 'Blue Sky' && tags.list().find((x) => x.id === sky).count === 2, 'tag created (normalized) and counted per hash')
assert(tags.add(['h2'], 'blue sky') === sky, 'tag names are case-insensitive')
const sel = tags.forHashes(['h1', 'h2'])
assert(sel.all.map((x) => x.name).join() === 'Blue Sky' && sel.some.map((x) => x.name).join() === '花卉', 'selection tags split into all / some')
const flower = tags.list().find((x) => x.name === '花卉').id
assert(hashesOf({ tagIds: [flower] }) === 'h1' && hashesOf({ tagIds: [flower, sky] }) === 'h1' && hashesOf({ tagIds: [sky] }) === 'h1,h2', 'tag filter (AND) in browse')
assert(tags.search('花卉照片', 10).map((x) => x.fileHash).join() === 'h1', 'tag channel matches jieba tokens')
assert(tags.search('blue', 10).length === 2, 'tag channel matches name prefix')
const merged = tags.rename(flower, 'BLUE SKY')
assert(merged === sky && !tags.get(flower) && tags.forHashes(['h1']).all.length === 1, 'rename onto an existing name merges')
tags.remove(['h1', 'h2'], sky)
assert(n('select count(*) n from tags') === 0, 'tag without items is GCd')
// 自动标签：自动链接 / 确认 / 删掉后记住拒绝 / 重跑不动用户标签 / 已有同名用户标签复用
const { AutoTagStore } = require(require('path').join(__dirname, '..', 'dist', 'cli', 'core', 'autotag', 'store.js'))
const at = new AutoTagStore(db.raw)
const vocab = new Map([['flower', { id: 'flower', facet: 'subject', zh: '花', en: 'Flowers', prompts: ['x'] }], ['sky', { id: 'sky', facet: 'scene', zh: '天空', en: 'Sky', prompts: ['x'] }]])
const userSky = tags.add(['h2'], 'sky')
at.apply('h1', 'v1', [{ labelId: 'flower', cosine: 0.8, z: 4 }, { labelId: 'sky', cosine: 0.79, z: 3.9 }], vocab)
const autoSel = tags.forHashes(['h1'])
assert(autoSel.all.length === 2 && autoSel.all.every((x) => x.auto), 'auto tags linked and marked auto')
assert(autoSel.all.find((x) => x.labelId === 'sky').id === userSky, 'auto label reuses an existing same-name user tag')
const flowerTag = autoSel.all.find((x) => x.labelId === 'flower').id
tags.confirmAuto(['h1'], flowerTag)
assert(!tags.forHashes(['h1']).all.find((x) => x.id === flowerTag).auto, 'confirm turns an auto tag into a user tag')
tags.remove(['h1'], userSky)
at.apply('h1', 'v1', [{ labelId: 'sky', cosine: 0.79, z: 3.9 }], vocab)
assert(!tags.forHashes(['h1']).all.some((x) => x.id === userSky), 'removed auto tag is not re-added (rejection remembered)')
at.reset()
assert(tags.forHashes(['h1']).all.map((x) => x.id).join() === String(flowerTag) && at.counts('v1').done === 0, 'rerun clears unconfirmed auto tags and done marks, keeps confirmed ones')
assert(tags.forHashes(['h2']).all.some((x) => x.id === userSky), 'user tags untouched by rerun')
assert(tags.search('Flowers', 10).map((x) => x.fileHash).join() === 'h1', 'vocabulary tag searchable by its other-language name')
tags.remove(['h1'], flowerTag)
tags.remove(['h2'], userSky)
// 标签随内容一起 GC：内容删掉后链接也删
tags.add(['h1'], 'gc-check')
// 收集箱：is_inbox 标记（迁移加列）+ item_sources 来源（第一次的不被覆盖，缺的字段补上）
const { CollectStore } = require(require('path').join(__dirname, '..', 'dist', 'cli', 'core', 'collectStore.js'))
const cs = new CollectStore(db.raw)
assert(cs.getInbox() === null, 'no inbox by default')
const inboxF = db.addFolder('/tmp/vx-inbox-smoke')
cs.markInbox(inboxF.id)
assert(cs.getInbox() && cs.getInbox().id === inboxF.id, 'is_inbox marked and found')
assert(db.getFolders().find((x) => x.id === inboxF.id).isInbox === true, 'getFolders maps isInbox')
cs.markInbox(f.id)
assert(cs.getInbox().id === f.id && db.getFolders().filter((x) => x.isInbox).length === 1, 'only one inbox at a time')
cs.markInbox(inboxF.id)
cs.setSource('h2', { url: 'https://a.com/x.jpg', pageTitle: 'T' })
cs.setSource('h2', { url: 'https://other.com/y.jpg', pageUrl: 'https://p.com/page' })
const src = cs.getSource('h2')
assert(src && src.url === 'https://a.com/x.jpg' && src.pageUrl === 'https://p.com/page' && src.pageTitle === 'T', 'item_sources keeps first url, fills missing fields')
assert(cs.liveImageByHash('h1') === p1 && cs.liveImageByHash('nope') === null, 'liveImageByHash dedupe lookup')
// 色板：保存 / 读取 / 颜色筛选（bucket_mask 位掩码）/ 回填查询
const { maskForColor } = require(require('path').join(__dirname, '..', 'dist', 'cli', 'shared', 'colors.js'))
db.saveItemColors('h1', JSON.stringify([{ hex: '#1e66d0', p: 0.6, bucket: 'blue' }, { hex: '#f5f5f5', p: 0.4, bucket: 'white' }]), maskForColor('blue') | maskForColor('white'))
const ic = db.getItemColors('h1')
assert(ic && (ic.mask & maskForColor('blue')) && JSON.parse(ic.palette)[0].bucket === 'blue', 'item_colors saved and read back')
assert(db.hasColorsForHash('h1') && !db.hasColorsForHash('h2'), 'hasColorsForHash')
assert(hashesOf({ color: 'blue' }) === 'h1' && hashesOf({ color: 'red' }) === '', 'color filter via bucket_mask in browse')
assert(hashesOf({ color: 'white', orientation: 'landscape' }) === 'h1', 'color filter combines with other filters')
assert(hashesOf({ color: 'nope' }) === '', 'unknown color name matches nothing')
assert([...db.getHashesForColorMask(maskForColor('blue'))].join() === 'h1', 'getHashesForColorMask set for search post-filter')
assert(db.getHashesMissingColors(10).map((x) => x.fileHash).includes('h2') && !db.getHashesMissingColors(10).map((x) => x.fileHash).includes('h1'), 'backfill query lists only hashes without colors')
db.saveItemColors('h1', JSON.stringify([{ hex: '#d92b2b', p: 1, bucket: 'red' }]), maskForColor('red'))
assert(hashesOf({ color: 'red' }) === 'h1' && hashesOf({ color: 'blue' }) === '', 'saveItemColors upserts (recompute overwrites)')
// folder delete GCs all
const orphans = db.deletePhotosByFolder(f.id)
assert(['h1','h2'].every(h => orphans.includes(h)), 'deletePhotosByFolder returns orphaned hashes')
assert(n('select count(*) n from image_vec_map') === 0, 'all vectors GCd')
assert(n('select count(*) n from image_ocr') === 0, 'OCR GCd')
assert(n('select count(*) n from favorites') === 0, 'favorites GCd with content')
assert(n('select count(*) n from item_tags') === 0, 'tag links GCd with content')
assert(n('select count(*) n from item_sources') === 0, 'item_sources GCd with content')
assert(n('select count(*) n from item_colors') === 0, 'item_colors GCd with content')
// smart albums: CRUD, JSON filters sanitized, order
const a1 = db.createSmartAlbum({ name: '', query: ' 花 ', filters: { orientation: 'portrait', favorite: true, bogus: 1, minPixels: 'x' } })
assert(a1.name === '花' && a1.query === '花', 'smart album default name = trimmed query')
assert(JSON.stringify(a1.filters) === JSON.stringify({ orientation: 'portrait', favorite: true }), 'smart album filters sanitized')
const a2 = db.createSmartAlbum({ name: 'Portrait', query: '', filters: { kind: 'image', dateFrom: '2024-01-01' } })
assert(db.getSmartAlbums().map((a) => a.id).join() === `${a1.id},${a2.id}`, 'smart albums listed in creation order')
const a1b = db.updateSmartAlbum(a1.id, { name: 'Flowers', filters: { minPixels: 8000000 } })
assert(a1b.name === 'Flowers' && a1b.query === '花' && a1b.filters.minPixels === 8000000 && !a1b.filters.orientation, 'smart album update keeps unspecified fields')
assert(db.updateSmartAlbum(a1.id, { name: '  ' }).name === 'Flowers', 'blank rename ignored')
db.reorderSmartAlbums([a2.id])
assert(db.getSmartAlbums().map((a) => a.id).join() === `${a2.id},${a1.id}`, 'smart albums reordered')
db.deleteSmartAlbum(a2.id)
assert(db.getSmartAlbums().length === 1 && db.updateSmartAlbum(a2.id, { name: 'x' }) === undefined, 'smart album deleted')
// 截图标记（is_screenshot：NULL = 未判，0/1 = 判过）+ 按标记筛选 + 回填查询 + live 任务队列
const sf = db.addFolder('/tmp/vx-shot-smoke')
const s1 = db.addPhoto(sf.id, '/tmp/vx-shot-smoke/shot.png', 'shot.png', 1, 1, 'sh1')
const s2 = db.addPhoto(sf.id, '/tmp/vx-shot-smoke/photo.jpg', 'photo.jpg', 1, 1, 'sh2')
db.saveImageVec('sh1', vec()); db.saveImageVec('sh2', vec())
assert(db.getScreenshotFlagForHash('sh1') === null, 'is_screenshot starts NULL (unknown)')
assert(db.photosMissingScreenshotFlag(10).some((p) => p.id === s1), 'backfill query lists unflagged photos')
db.setPhotoScreenshot(s1, 1); db.setPhotoScreenshot(s2, 0)
assert(db.getScreenshotFlagForHash('sh1') === 1 && db.getScreenshotFlagForHash('sh2') === 0, 'flag set and read back per hash')
assert(!db.photosMissingScreenshotFlag(10).some((p) => p.id === s1 || p.id === s2), 'flagged photos leave the backfill list')
const shots = db.getRepresentativePhotosFiltered(50, 0, { screenshot: true })
assert(shots.length === 1 && shots[0].fileHash === 'sh1' && shots[0].isScreenshot === 1, 'screenshot filter returns only flagged items')
assert(db.getPhoto(s1).isScreenshot === 1, 'getPhoto maps isScreenshot')
// 任务来源：live 任务在电源策略等待时仍可取
db.addToQueue(s1, 'thumbnail', 20, 'live')
db.addToQueue(s2, 'thumbnail', 20) // 默认 backfill
assert(db.countLivePendingTasks() === 1, 'live pending count')
const liveTask = db.getNextTask(true)
assert(liveTask && liveTask.photoId === s1 && liveTask.origin === 'live', 'getNextTask(liveOnly) skips backfill tasks')
assert(db.getNextTask(true) === undefined, 'no more live tasks')
const bfTask = db.getNextTask()
assert(bfTask && bfTask.photoId === s2 && bfTask.origin === 'backfill', 'backfill task still reachable without liveOnly')
db.completeTask(liveTask.id); db.completeTask(bfTask.id)
// 跳过的数据集目录：登记 / 列出 / override / 随文件夹删除
db.addSkippedFolder(sf.id, '/tmp/vx-shot-smoke/frames', 250)
db.addSkippedFolder(sf.id, '/tmp/vx-shot-smoke/frames', 260) // upsert 更新计数
let sk = db.listSkippedFolders(sf.id)
assert(sk.length === 1 && sk[0].fileCount === 260 && sk[0].override === false && sk[0].reason === 'dataset', 'skipped folder recorded (upsert keeps one row)')
db.setSkippedFolderOverride('/tmp/vx-shot-smoke/frames', true)
assert(db.listSkippedFolders(sf.id)[0].override === true, 'override persisted')
assert(db.listSkippedFolders().length >= 1, 'listSkippedFolders without folderId lists all')
db.deletePhotosByFolder(sf.id)
db.removeFolder(sf.id)
assert(db.listSkippedFolders(sf.id).length === 0, 'skipped folders removed with their watched folder')
// readonly reopen
db.close()
const ro = initDatabase(path, { readonly: true })
assert(ro.getFolders().length === 2, 'readonly open works')
assert(ro.getFolders().find((x) => x.isInbox).path === '/tmp/vx-inbox-smoke', 'readonly open maps isInbox')
try { ro.addFolder('/x'); assert(false, 'readonly rejects writes') } catch { assert(true, 'readonly rejects writes') }
ro.close()
